export function formatPrice(price, type) {
  return type === 'For rent'
    ? `$${price.toLocaleString()} / mo`
    : new Intl.NumberFormat('en-US', {
      style: 'currency',
      currency: 'USD',
      notation: 'compact',
      maximumFractionDigits: 3,
    }).format(price)
}
